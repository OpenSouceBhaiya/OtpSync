let currentLang = 'en';

function getTranslation(key, lang = currentLang) {
  if (I18N_TRANSLATIONS[lang] && I18N_TRANSLATIONS[lang][key]) {
    return I18N_TRANSLATIONS[lang][key];
  }
  if (I18N_TRANSLATIONS['en'] && I18N_TRANSLATIONS['en'][key]) {
    return I18N_TRANSLATIONS['en'][key];
  }
  return key;
}

function setAppLanguage(langCode) {
  if (!I18N_TRANSLATIONS[langCode]) langCode = 'en';
  currentLang = langCode;
  try {
    chrome.storage.local.set({ appLanguage: langCode });
  } catch(e) {}
  applyTranslationsToDom();
}

function applyTranslationsToDom() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const trans = getTranslation(key);
    if (trans) {
      if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
        el.setAttribute('placeholder', trans);
      } else {
        el.textContent = trans;
      }
    }
  });
}

window.I18N = {
  translations: I18N_TRANSLATIONS,
  languages: AVAILABLE_LANGUAGES,
  getTranslation: getTranslation,
  getCurrentLanguage: () => currentLang,
  getAvailableLanguages: () => AVAILABLE_LANGUAGES,
  setAppLanguage: setAppLanguage,
  applyTranslations: applyTranslationsToDom
};

// Auto-initialize when loaded
try {
  chrome.storage.local.get(['appLanguage'], (res) => {
    if (res && res.appLanguage && I18N_TRANSLATIONS[res.appLanguage]) {
      currentLang = res.appLanguage;
    }
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', applyTranslationsToDom);
    } else {
      applyTranslationsToDom();
    }
  });
} catch(e) {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslationsToDom);
  } else {
    applyTranslationsToDom();
  }
}

